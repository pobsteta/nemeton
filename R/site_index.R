#' List species covered by the site-index curves
#'
#' Returns the species codes available in
#' \code{inst/extdata/site_index_curves.csv}. Codes
#' \code{BROADLEAF_GENUS} and \code{CONIFER_GENUS} are
#' genus-level fallbacks automatically used when the input
#' species is not directly tabulated.
#'
#' @return A character vector of species codes.
#'
#' @examples
#' list_site_index_species()
#'
#' @export
list_site_index_species <- function() {
  curves <- read_site_index_curves()
  sort(unique(curves$species))
}


#' Published calibration points for the site-index curves
#'
#' Returns the set of per-species \eqn{(age, H_{class\_3})}
#' reference points against which the parameters in
#' \code{data-raw/site_index_curves.R} are tuned. Each row
#' carries the source citation so that downstream users can
#' audit the provenance of the curves, and the regression test
#' \code{test-site-index-calibration.R} asserts that the
#' generated CSV reproduces these points within a 0.5 m
#' tolerance (class_3 at the stated reference age).
#'
#' For Phase A species, the underlying equations differ (Duplat
#' & Tran-Ha 1997, Seynave 2005, Vallet & Pérot 2011…) but the
#' current Chapman-Richards approximation is calibrated to match
#' one published point per species. For FASY the full Korf model
#' from Bontemps et al. 2007 is used, so its calibration point
#' is the H(100) produced by the Bontemps parameters themselves.
#'
#' @return A data.frame with columns \code{species, age, h_class_3,
#'   source}.
#'
#' @examples
#' site_index_reference_points()
#'
#' @export
site_index_reference_points <- function() {
  data.frame(
    species   = c("QUPE", "QURO", "FASY", "CASA",
                  "PIAB", "ABAL", "PSME", "PISY",
                  "PIPI", "POSP"),
    age       = c(100L, 100L, 100L, 80L,
                  50L,  50L,  50L,  50L,
                  40L,  25L),
    h_class_3 = c(24.0, 22.0, 29.2, 22.0,
                  22.0, 20.0, 27.5, 16.5,
                  17.5, 23.5),
    source    = c("Duplat & Tran-Ha 1997",
                  "Duplat & Tran-Ha 1997",
                  "Bontemps et al. 2007 (Korf, NO+NE mean)",
                  "Dh\u00f4te-like scaling (IFN 2004)",
                  "Seynave et al. 2005",
                  "Vallet & P\u00e9rot 2011",
                  "DSF / IRSTEA 2010",
                  "Duplat 2001 follow-up",
                  "Lemoine 1991 (IFN Landes)",
                  "CNPF 2013 (peupleraie)"),
    stringsAsFactors = FALSE
  )
}


#' Estimate the site index from a dominant height and a stand age
#'
#' Given an observed dominant height \code{H_dom} (typically
#' derived from a Canopy Height Model) and the stand age, returns
#' the dominant height that the same fertility level would reach
#' at \code{reference_age}. This is the classical definition of
#' the site index in French forestry.
#'
#' The computation is a bilinear interpolation over the five
#' fertility classes tabulated in
#' \code{inst/extdata/site_index_curves.csv}:
#' \enumerate{
#'   \item At the observed \code{age}, find which pair of
#'         fertility classes brackets \code{H_dom}, and compute
#'         the fractional class \code{c} in \code{[1, 5]}.
#'   \item At \code{reference_age}, interpolate between the same
#'         pair of classes using \code{c}.
#' }
#'
#' When \code{species} is not directly tabulated, a genus-level
#' fallback is applied (\code{BROADLEAF_GENUS} for non-conifers,
#' \code{CONIFER_GENUS} otherwise).
#'
#' @param H_dom Numeric vector. Observed dominant height in
#'   metres.
#' @param age Numeric vector. Stand age in years.
#' @param species Character vector. Species codes (IFN style,
#'   4 letters). Recycled against \code{H_dom} / \code{age}.
#' @param reference_age Numeric scalar. Reference age at which
#'   the site index is returned (default 50).
#'
#' @return A numeric vector of the same length as the recycled
#'   inputs, giving the site index (dominant height at
#'   \code{reference_age}) in metres. \code{NA} is returned when
#'   \code{H_dom} or \code{age} is missing, when \code{age} is
#'   outside the tabulated range, or when the species cannot be
#'   resolved.
#'
#' @examples
#' # Sessile oak: 20 m at 80 years -> site index at 50 years
#' compute_site_index(H_dom = 20, age = 80, species = "QUPE")
#'
#' # Norway spruce: 25 m at 40 years
#' compute_site_index(H_dom = 25, age = 40, species = "PIAB")
#'
#' # Vectorised input
#' compute_site_index(
#'   H_dom   = c(20, 25, 18),
#'   age     = c(80, 40, 60),
#'   species = c("QUPE", "PIAB", "FASY")
#' )
#'
#' @export
compute_site_index <- function(H_dom,
                               age,
                               species,
                               reference_age = 50) {

  n <- max(length(H_dom), length(age), length(species))
  if (n == 0) return(numeric(0))

  H_dom   <- rep_len(H_dom, n)
  age     <- rep_len(age, n)
  species <- rep_len(as.character(species), n)

  if (!is.numeric(reference_age) || length(reference_age) != 1L ||
      is.na(reference_age) || reference_age <= 0) {
    stop("reference_age must be a positive scalar.", call. = FALSE)
  }

  curves    <- read_site_index_curves()
  available <- unique(curves$species)
  class_cols <- paste0("class_", 1:5)

  out <- numeric(n)

  for (i in seq_len(n)) {
    h_i <- H_dom[i]
    a_i <- age[i]
    s_i <- species[i]

    if (is.na(h_i) || is.na(a_i) || is.na(s_i) || h_i < 0 || a_i <= 0) {
      out[i] <- NA_real_
      next
    }

    sp_key <- resolve_species_code(s_i, available)
    if (is.na(sp_key)) {
      out[i] <- NA_real_
      next
    }

    sub <- curves[curves$species == sp_key, ]
    sub <- sub[order(sub$age), ]

    # Interpolate heights for each class at the observed age
    h_at_age <- vapply(class_cols, function(col) {
      stats::approx(x = sub$age, y = sub[[col]],
                    xout = a_i, rule = 1)$y
    }, numeric(1))

    if (anyNA(h_at_age)) {
      out[i] <- NA_real_
      next
    }

    # Heights at observed age are decreasing from class 1 to class 5
    # (best -> worst). Find which two classes bracket h_i.
    frac_class <- .frac_class(h_i, h_at_age)
    if (is.na(frac_class)) {
      out[i] <- NA_real_
      next
    }

    # Interpolate heights at reference_age per class
    h_at_ref <- vapply(class_cols, function(col) {
      stats::approx(x = sub$age, y = sub[[col]],
                    xout = reference_age, rule = 1)$y
    }, numeric(1))

    if (anyNA(h_at_ref)) {
      out[i] <- NA_real_
      next
    }

    # Linear interpolation between the bracketing classes at ref age
    lo <- floor(frac_class)
    hi <- min(lo + 1, 5L)
    if (lo < 1L) lo <- 1L
    w  <- frac_class - lo
    out[i] <- (1 - w) * h_at_ref[lo] + w * h_at_ref[hi]
  }

  out
}


# Helper: given an observed H and the 5 heights at a given age
# (ordered class 1 = tallest to class 5 = shortest), return a
# fractional class index in [1, 5]. Returns NA if H is outside
# the extrapolation range (clamped).
#
# @keywords internal
.frac_class <- function(h, h_classes) {
  # h_classes length 5, monotonically decreasing
  # Clamp to the tabulated range — out-of-range heights map to
  # the nearest class boundary.
  if (h >= h_classes[1]) return(1)
  if (h <= h_classes[5]) return(5)

  for (k in 1:4) {
    upper <- h_classes[k]     # tallest between k and k+1
    lower <- h_classes[k + 1] # shortest
    if (h <= upper && h >= lower) {
      if (upper == lower) return(k + 0.5)
      w <- (upper - h) / (upper - lower)
      return(k + w)
    }
  }
  NA_real_
}
