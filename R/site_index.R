#' Site-index curves and estimation
#'
#' Reads the site-index reference CSV shipped with the package
#' and exposes helpers to estimate a stand site index from an
#' observed dominant height and age.
#'
#' These functions support the CHM-driven mode of
#' \code{\link{indicateur_p2_station}} (spec 005, phase 2). When a
#' Canopy Height Model is available, the CHM provides \eqn{H_{dom}},
#' the stand age is read from BD Forêt / inventory data, and
#' \code{compute_site_index()} returns the dominant height at a
#' reference age (by default 50 years), which is the classical
#' forestry definition of the site index.
#'
#' The curves are loaded once per R session from
#' \code{inst/extdata/site_index_curves.csv} and cached in an
#' internal environment.
#'
#' @name site_index
#' @keywords internal
NULL


# ============================================================
# Internal cache
# ============================================================

.site_index_cache <- new.env(parent = emptyenv())


#' Read the site-index reference curves
#'
#' Returns the full table of reference site-index curves shipped
#' with the package, with a per-session cache. The CSV is
#' generated by \code{data-raw/site_index_curves.R}.
#'
#' @return A \code{data.frame} with columns \code{species, age,
#'   class_1, ..., class_5}. Heights in metres.
#'
#' @examples
#' curves <- read_site_index_curves()
#' head(curves)
#'
#' @export
read_site_index_curves <- function() {
  if (!is.null(.site_index_cache$curves)) {
    return(.site_index_cache$curves)
  }

  path <- system.file("extdata", "site_index_curves.csv",
                      package = "nemeton")
  if (!nzchar(path) || !file.exists(path)) {
    stop("site_index_curves.csv not found in package extdata.",
         call. = FALSE)
  }

  curves <- utils::read.csv(path, stringsAsFactors = FALSE)

  required <- c("species", "age", paste0("class_", 1:5))
  missing <- setdiff(required, names(curves))
  if (length(missing) > 0) {
    stop("site_index_curves.csv is missing columns: ",
         paste(missing, collapse = ", "), call. = FALSE)
  }

  .site_index_cache$curves <- curves
  curves
}


